"""Destination checks for connector URLs, on top of the ``UPSTREAM_ALLOWED_HOSTS`` allow-list.

The allow-list decides which host names may be used. This module decides which *addresses*
those names may resolve to, so a broad pattern (``*:443``) or a DNS record that changes later
(DNS rebinding) cannot point the gateway at internal services:

* Never: link-local and cloud metadata addresses (``169.254.0.0/16``, ``fe80::/10``,
  ``fd00:ec2::254``, ``100.100.100.200``), multicast, unspecified and reserved ranges.
* Private, loopback, CGNAT and unique-local addresses only when the URL's host is named
  exactly in the allow-list (no ``*`` in the host part), e.g.
  ``woocommerce-mcp.urumi.svc.cluster.local:8000``: the operator explicitly chose that
  internal service.

Checked when a connector is registered or its URL changes, and again before every call, because
DNS answers can change after registration. Hosted servers are exempt: their URL is generated by
the gateway itself.
"""

from __future__ import annotations

import asyncio
import ipaddress
import socket
from urllib.parse import urlsplit

from gateway.config import UpstreamSettings

_METADATA = {
    ipaddress.ip_address("169.254.169.254"),
    ipaddress.ip_address("fd00:ec2::254"),
    ipaddress.ip_address("100.100.100.200"),
}
_CGNAT = ipaddress.ip_network("100.64.0.0/10")

IpAddress = ipaddress.IPv4Address | ipaddress.IPv6Address


class DestinationBlockedError(Exception):
    """The URL resolves to an address the gateway must not connect to. ``reason`` is safe to
    show to platform admins; it names the address class, not the address."""

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


def classify(address: IpAddress) -> str | None:
    """'forbidden', 'internal' or None (public)."""
    if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped:
        address = address.ipv4_mapped
    if (
        address in _METADATA
        or address.is_link_local
        or address.is_multicast
        or address.is_unspecified
        or address.is_reserved
    ):
        return "forbidden"
    if address.is_loopback or address.is_private or address in _CGNAT:
        return "internal"
    return None


_FAMILIES = {"auto": socket.AF_UNSPEC, "ipv4": socket.AF_INET, "ipv6": socket.AF_INET6}


async def resolve(host: str, port: int, *, family: str = "auto") -> set[IpAddress]:
    try:
        return {ipaddress.ip_address(host)}
    except ValueError:
        pass
    loop = asyncio.get_running_loop()
    try:
        # Same address family as the connection itself (UPSTREAM_IP_FAMILY), so this lookup
        # sees what httpx will use and avoids the macOS IPv6 stall on *.local names.
        infos = await loop.getaddrinfo(
            host, port, family=_FAMILIES[family], type=socket.SOCK_STREAM
        )
    except socket.gaierror as exc:
        raise DestinationBlockedError("the host name does not resolve") from exc
    return {ipaddress.ip_address(info[4][0]) for info in infos}


async def check_destination(url: str, settings: UpstreamSettings) -> None:
    parts = urlsplit(url)
    host = (parts.hostname or "").lower()
    port = parts.port or (443 if parts.scheme == "https" else 80)
    exact = settings.is_exactly_allowed(host, port)
    for address in await resolve(host, port, family=settings.ip_family):
        kind = classify(address)
        if kind == "forbidden":
            raise DestinationBlockedError(
                "it resolves to a link-local, metadata or reserved address"
            )
        if kind == "internal" and not exact:
            raise DestinationBlockedError(
                "it resolves to a private address, which needs the exact host in "
                "UPSTREAM_ALLOWED_HOSTS (no wildcard)"
            )
